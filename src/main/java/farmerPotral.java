    // Helper method to setup table columns
    private void setupTable() {
        String[] columnNames = {"Crop Name", "Planting Date", "Growth Stage", "Expected Harvest", "Status"};
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        jTable1.setModel(model);
        jTable1.setRowHeight(30);
        jTable1.setFont(new Font("Arial", Font.PLAIN, 13));
        jTable1.getTableHeader().setFont(new Font("Arial", Font.BOLD, 13));
        jTable1.getTableHeader().setBackground(new Color(34, 139, 34));
        jTable1.getTableHeader().setForeground(Color.WHITE);
    }

    // Load crops from database into table
    private void loadCropsFromDatabase() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing rows

        List<Object[]> crops = FarmerCropDAO.getAllCrops(currentFarmerId);

        for (Object[] crop : crops) {
            model.addRow(crop);
        }
    }

