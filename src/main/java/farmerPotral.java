    // Create tools panel with table
    private JPanel createToolsPanel() {
        JPanel panel = new JPanel(new BorderLayout(10, 10));
        panel.setBorder(BorderFactory.createEmptyBorder(15, 15, 15, 15));
        panel.setBackground(Color.WHITE);

        // Title
        JLabel titleLabel = new JLabel("🔧 My Tools");
        titleLabel.setFont(new Font("Arial", Font.BOLD, 18));
        titleLabel.setForeground(new Color(0, 123, 255));

        // Create table
        String[] columnNames = {"Tool Name", "Condition", "Last Used", "Status"};
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        JTable toolsTable = new JTable(model);
        toolsTable.setRowHeight(30);
        toolsTable.setFont(new Font("Arial", Font.PLAIN, 13));
        toolsTable.getTableHeader().setFont(new Font("Arial", Font.BOLD, 13));
        toolsTable.getTableHeader().setBackground(new Color(0, 123, 255));
        toolsTable.getTableHeader().setForeground(Color.WHITE);
        toolsTable.setSelectionBackground(new Color(173, 216, 230));

        // Load tools from database
        List<Object[]> tools = InventoryDAO.getAllTools(currentFarmerId);
        for (Object[] tool : tools) {
            model.addRow(tool);
        }

        JScrollPane scrollPane = new JScrollPane(toolsTable);
        scrollPane.setBorder(BorderFactory.createLineBorder(new Color(0, 123, 255), 2));

        panel.add(titleLabel, BorderLayout.NORTH);
        panel.add(scrollPane, BorderLayout.CENTER);

        return panel;
    }

    // Create seeds panel with table
    private JPanel createSeedsPanel() {
        JPanel panel = new JPanel(new BorderLayout(10, 10));
        panel.setBorder(BorderFactory.createEmptyBorder(15, 15, 15, 15));
        panel.setBackground(Color.WHITE);

        // Title
        JLabel titleLabel = new JLabel("🌱 My Seeds Stock");
        titleLabel.setFont(new Font("Arial", Font.BOLD, 18));
        titleLabel.setForeground(new Color(40, 167, 69));

        // Create table
        String[] columnNames = {"Seed Name", "Quantity", "Unit", "Status"};
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        JTable seedsTable = new JTable(model);
        seedsTable.setRowHeight(30);
        seedsTable.setFont(new Font("Arial", Font.PLAIN, 13));
        seedsTable.getTableHeader().setFont(new Font("Arial", Font.BOLD, 13));
        seedsTable.getTableHeader().setBackground(new Color(40, 167, 69));
        seedsTable.getTableHeader().setForeground(Color.WHITE);
        seedsTable.setSelectionBackground(new Color(144, 238, 144));

        // Load seeds from database
        List<Object[]> seeds = InventoryDAO.getAllSeeds(currentFarmerId);
        for (Object[] seed : seeds) {
            model.addRow(seed);
        }

        JScrollPane scrollPane = new JScrollPane(seedsTable);
        scrollPane.setBorder(BorderFactory.createLineBorder(new Color(40, 167, 69), 2));

        panel.add(titleLabel, BorderLayout.NORTH);
        panel.add(scrollPane, BorderLayout.CENTER);

        return panel;
    }

