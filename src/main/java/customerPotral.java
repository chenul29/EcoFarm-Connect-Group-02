    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Buy Product functionality
        int selectedRow = jTable1.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a product to buy!", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get product details from selected row
        int productId = (int) jTable1.getValueAt(selectedRow, 0);
        String productName = (String) jTable1.getValueAt(selectedRow, 1);
        String farmerName = (String) jTable1.getValueAt(selectedRow, 2);
        String priceStr = (String) jTable1.getValueAt(selectedRow, 3);
        String availableStr = (String) jTable1.getValueAt(selectedRow, 4);

        // Get full product details
        Object[] product = MarketplaceDAO.getProductById(productId);
        if (product == null) {
            JOptionPane.showMessageDialog(this, "Product not found!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double price = (double) product[3];
        int availableQty = (int) product[4];
        String unit = (String) product[5];

        // Ask for quantity
        String quantityStr = JOptionPane.showInputDialog(this,
            "Enter quantity to purchase (Available: " + availableQty + " " + unit + "):",
            "Purchase Quantity",
            JOptionPane.QUESTION_MESSAGE);

        if (quantityStr == null || quantityStr.trim().isEmpty()) {
            return; // User cancelled
        }

        try {
            int quantity = Integer.parseInt(quantityStr);

            if (quantity <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity must be greater than 0!", "Invalid Quantity", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (quantity > availableQty) {
                JOptionPane.showMessageDialog(this, "Not enough stock! Available: " + availableQty + " " + unit, "Insufficient Stock", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Calculate total
            double totalAmount = price * quantity;

            // Confirm purchase
            int confirm = JOptionPane.showConfirmDialog(this,
                "Product: " + productName + "\n" +
                "Farmer: " + farmerName + "\n" +
                "Quantity: " + quantity + " " + unit + "\n" +
                "Price: $" + price + "/" + unit + "\n" +
                "Total: $" + totalAmount + "\n\n" +
                "Confirm purchase?",
                "Confirm Purchase",
                JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                // Add order to database
                boolean success = CustomerOrderDAO.addOrder(
                    customerName,
                    productId,
                    productName,
                    farmerName,
                    quantity,
                    unit,
                    price,
                    totalAmount
                );

                if (success) {
                    JOptionPane.showMessageDialog(this,
                        "Order placed successfully!\n" +
                        "Total Amount: $" + totalAmount + "\n" +
                        "Order Status: Pending",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);

                    // Refresh the product list
                    loadMarketplaceProducts();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to place order!", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number!", "Invalid Input", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

