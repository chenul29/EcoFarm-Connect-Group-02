    // Load marketplace products from database
    private void loadMarketplaceProducts() {
        // Create table if not exists
        MarketplaceDAO.createMarketplaceTable();
        CustomerOrderDAO.createOrdersTable();

        // Get all approved products
        List<Object[]> products = MarketplaceDAO.getAllProducts();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing rows

        for (Object[] product : products) {
            // Only show approved products
            if ("Approved".equals(product[6])) {
                // Get category from database
                int productId = (int) product[0];
                Object[] fullProduct = MarketplaceDAO.getProductById(productId);
                String category = fullProduct != null ? (String) fullProduct[6] : "N/A";

                Object[] row = {
                    product[0],  // ID
                    product[1],  // Product Name
                    product[2],  // Farmer Name
                    product[3],  // Price
                    product[4],  // Available Quantity
                    category,    // Category
                    product[5]   // Status
                };
                model.addRow(row);
            }
        }
    }

